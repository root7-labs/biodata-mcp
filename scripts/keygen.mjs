#!/usr/bin/env node
// Licence key tooling for BioData MCP.
//   npm run keys:init                         -> creates keys/private.pem (KEEP SECRET) and writes the public key into src/license-pubkey.ts
//   npm run keys:issue -- buyer@email.com 365 -> prints a Pro key valid for 365 days (use 0 for no expiry)
import { generateKeyPairSync, createPrivateKey, sign } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const privPath = join(root, "keys", "private.pem");
const pubTs = join(root, "src", "license-pubkey.ts");

const [cmd, ...args] = process.argv.slice(2);

function b64url(buf) {
  return Buffer.from(buf).toString("base64").replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}

if (cmd === "init") {
  if (existsSync(privPath)) {
    console.error(`Refusing to overwrite existing ${privPath}. Delete it yourself if you really want new keys (old licence keys will stop working).`);
    process.exit(1);
  }
  const { publicKey, privateKey } = generateKeyPairSync("ed25519");
  mkdirSync(dirname(privPath), { recursive: true });
  writeFileSync(privPath, privateKey.export({ type: "pkcs8", format: "pem" }), { mode: 0o600 });
  const pem = publicKey.export({ type: "spki", format: "pem" }).toString().trim();
  writeFileSync(
    pubTs,
    `// Generated by \`npm run keys:init\`. Safe to publish.\nexport const PUBLIC_KEY_PEM = ${JSON.stringify(pem)};\n`,
  );
  console.log(`Created ${privPath} (never commit or share this file)`);
  console.log(`Wrote public key to ${pubTs}. Run npm run build before publishing.`);
} else if (cmd === "issue") {
  const [email, daysArg = "365", plan = "pro"] = args;
  if (!email) {
    console.error("Usage: npm run keys:issue -- buyer@email.com [days=365|0] [plan=pro]");
    process.exit(1);
  }
  if (!existsSync(privPath)) {
    console.error("No private key found. Run npm run keys:init first.");
    process.exit(1);
  }
  const days = Number(daysArg);
  const payload = {
    sub: email,
    plan,
    iat: new Date().toISOString(),
    exp: days > 0 ? new Date(Date.now() + days * 86_400_000).toISOString() : null,
  };
  const payloadB64 = b64url(JSON.stringify(payload));
  const sig = sign(null, Buffer.from(payloadB64), createPrivateKey(readFileSync(privPath)));
  console.log(`bd1.${payloadB64}.${b64url(sig)}`);
} else {
  console.error("Commands: init | issue <email> [days] [plan]");
  process.exit(1);
}
